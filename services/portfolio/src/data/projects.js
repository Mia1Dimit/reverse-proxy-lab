const STATUS_ORDER = { live: 0, research: 1, wip: 2 };
export function sortByStatus(projects) {
  return [...projects].sort((a, b) => STATUS_ORDER[a.status] - STATUS_ORDER[b.status]);
}

export function matchesStatus(project, status) {
  return status === 'All' || project.status === status.toLowerCase() || (status === 'WIP' && project.inProgress);
}
